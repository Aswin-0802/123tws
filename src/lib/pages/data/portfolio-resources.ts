const live = (slug: string, file: string) => `/images/live/${slug}/${file}`;

const logo = (title: string, file: string): GalleryItem => ({
  title,
  caption: "Logo design",
  image: { src: live("logos", file), alt: `${title} logo design by 123 Total Web Solutions`, fit: "contain" },
});

const brochure = (title: string, file: string, pages: string[] = []): GalleryItem => ({
  title,
  caption: "Brochure design",
  image: { src: live("brochures", file), alt: `${title} brochure design by 123 Total Web Solutions`, fit: "contain" },
  ...(pages.length
    ? {
        pages: pages.map((p, i) => ({
          src: live("brochures", p),
          alt: `${title} brochure, page ${i + 2}`,
          fit: "contain" as const,
        })),
      }
    : {}),
});

const poster = (title: string, file: string): GalleryItem => ({
  title,
  caption: "Social media post",
  image: {
    src: live("social-media-posters", file),
    alt: `Social media post designed for ${title} by 123 Total Web Solutions`,
    fit: "contain",
  },
});

const site = (title: string, caption: string, file: string, href?: string): GalleryItem => ({
  title,
  caption,
  image: { src: live("portfolio", file), alt: `${title} website designed by 123 Total Web Solutions`, fit: "cover" },
  ...(href ? { href } : {}),
});

const BLOG = "https://www.123tws.com/blog/";

const post = (title: string, path: string, file: string, topic: string): GalleryItem => ({
  title,
  caption: topic,
  href: `${BLOG}${path}`,
  image: { src: live("blog", file), alt: `Cover image for the article: ${title}`, fit: "contain" },
});

const caseStudy = (title: string, path: string, file: string, topic: string): GalleryItem => ({
  title,
  caption: topic,
  href: `https://www.123tws.com/case-study/${path}`,
  image: { src: live("case-study", file), alt: `Cover image for the case study: ${title}`, fit: "contain" },
});

